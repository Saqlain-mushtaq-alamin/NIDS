def _resolve(components: list[str]) -> list[str]:
    """Order ``components`` so every dependency runs first (once)."""
    ordered: list[str] = []

    def visit(name: str) -> None:
        if name in ordered:
            return
        for dep in DEPENDENCIES.get(name, ()):
            visit(dep)
        if name not in ordered:
            ordered.append(name)

    for name in components:
        visit(name)
    return ordered


