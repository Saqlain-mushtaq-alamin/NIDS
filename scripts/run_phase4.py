def _environment() -> dict:
    import platform

    env = {"python": platform.python_version(), "platform": platform.platform()}
    for module in ("shap", "captum", "streamlit", "xgboost", "torch"):
        try:
            imported = __import__(module)
            env[module] = getattr(imported, "__version__", "unknown")
        except Exception:
            env[module] = "not installed"
    return env


def _build_gates(report: dict, quick: bool) -> dict:
    """
    Phase 4 completion gates (PHASE_4 section 4.7).

    Quick mode is a smoke run: gates that need data volume are reported as
    ``null`` rather than quietly passed or failed.
    """
    def _unknown(detail: str) -> dict:
        return {"pass": None, "detail": detail}

    components = report.get("components", {})
    shap_block = components.get("shap") or {}
    faithful = components.get("faithfulness") or {}
    tiered_block = components.get("tiered") or {}
    response = components.get("response") or {}

    gates = {}

    tree_ms = (shap_block.get("benchmark") or {}).get("mean_ms_per_alert")
    gates["G4.1_tree_shap_latency"] = (
        _unknown("quick mode") if quick else
        {"pass": tree_ms is not None and tree_ms < 50.0,
         "detail": f"{tree_ms:.3f} ms/alert (budget 50 ms)"}
        if tree_ms is not None else _unknown("no benchmark"))

    n_faithful = faithful.get("n_alerts", 0)
    min_alerts = 100
    gates["G4.2_faithfulness_sample_size"] = (
        _unknown(f"quick mode ({n_faithful} alerts)") if quick else
        {"pass": n_faithful >= min_alerts,
         "detail": f"{n_faithful} alerts (gate >= {min_alerts})"})

    gates["G4.3_tier1_attack_type_coverage"] = {
        "pass": bool((tiered_block.get("coverage") or {}).get("all_covered")),
        "detail": str((tiered_block.get("coverage") or {}).get("missing"))}

    max_chars = tiered_block.get("tier1_max_chars", 0)
    gates["G4.4_tier1_concise"] = {
        "pass": max_chars < 500,
        "detail": f"longest summary {max_chars} chars (FR6 budget 500)"}

    tiers = response.get("tiers_exercised") or []
    gates["G4.5_response_tiers_exercised"] = {
        "pass": set(tiers) >= {"LOG_ONLY", "RATE_LIMIT", "BLOCK"},
        "detail": f"observed {tiers}"}

    burst = response.get("burst_test") or {}
    gates["G4.6_rate_limiter_bounds_blocks_NFR10"] = {
        "pass": bool(burst.get("rate_limiter_engaged")),
        "detail": (f"{burst.get('n_blocked')} blocks of "
                   f"{burst.get('n_attempted')} attempts at "
                   f"{burst.get('max_blocks_per_minute')}/min")}

    rollback = response.get("rollback_demo") or {}
    ttl = response.get("auto_unblock_demo") or {}
    gates["G4.7_rollback_and_ttl_unblock"] = {
        "pass": bool(rollback.get("succeeded")) and bool(ttl.get("succeeded")),
        "detail": (f"manual rollback={rollback.get('succeeded')}, "
                   f"ttl expiry={ttl.get('succeeded')}")}

    return gates


