"""
scripts/run_phase4.py — Combined Phase 4 driver (Explainability & Response).

Runs every Phase 4 component end to end and writes one consolidated report:

* **shap** — TreeSHAP attributions for every alert the XGBoost detector raises,
  plus the global summary plot and a per-alert explanation-latency benchmark.
* **deeplift** — DeepLIFT (Captum) attributions for the same alerts on the DNN
  classifier, plus its latency benchmark.
* **faithfulness** — deletion-AUC comparison of KernelSHAP vs DeepLIFT on the
  *same* alerts and the *same* model, with a paired t-test (PHASE_4 4.3).
* **tiered** — Tier-1 SOC triage summaries and Tier-2 full attribution payloads
  for the alerts, with coverage across every attack type.
* **response** — the alerts replayed through the tiered response engine in
  dry-run mode, plus a rate-limit burst test (NFR10), a manual rollback demo
  and an automatic TTL-unblock demo.
* **dashboard** — the bundle ``src/dashboard/app.py`` renders.

Artifacts land in ``results/phase4/``; ``docs/phase4_summary.md`` cites them.

Data provenance: the lab captures are synthetic stand-ins generated by
``src/data/traffic_model.py`` (see docs/phase2_summary.md).  The report repeats
that disclaimer: these numbers show that the explanation and response pipeline
is correct, not that any explanation is faithful to real-world intrusion
detection.

Examples::

    python scripts/run_phase4.py
    python scripts/run_phase4.py --quick
    python scripts/run_phase4.py --components shap response
"""
