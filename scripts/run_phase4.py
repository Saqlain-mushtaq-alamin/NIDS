def run_dashboard(ctx: Phase4Context, tiered_result: dict | None = None,
                  response_result: dict | None = None,
                  shap_result: dict | None = None, **_) -> dict:
    """Bundle the alert feed, traffic timeline and benchmarks the app renders."""
    import pandas as pd

    alerts = (tiered_result or {}).get("_alerts")
    if alerts is None:
        raise RuntimeError("Dashboard component needs the tiered component.")

    actions = {entry.get("alert_id"): entry.get("action")
               for entry in (response_result or {}).get("log", [])}
    dashboard_alerts = []
    for alert in alerts:
        payload = {
            "alert_id": alert["alert_id"],
            "label": alert["label"],
            "confidence": alert["confidence"],
            "severity": alert["severity"],
            "recommended_action": alert["recommended_action"],
            "source_ip": alert["source_ip"],
            "session_id": alert.get("session_id"),
            "true_label": alert.get("true_label"),
            "feature_names": alert["feature_names"],
            "shap_values": alert["shap_values"],
            "deeplift_values": alert.get("deeplift_values"),
            "top_features": alert["top_features"],
            "tier1": alert["tier1"],
            "action": actions.get(alert["alert_id"]),
        }
        dashboard_alerts.append(payload)

    # --- traffic timeline: flows per 60 s bucket, benign vs attack ---------
    frame = ctx.test_df[["timestamp_start", "label"]].copy()
    frame["timestamp_start"] = frame["timestamp_start"].astype(float)
    origin = float(frame["timestamp_start"].min())
    frame["bucket"] = ((frame["timestamp_start"] - origin) // 60).astype(int)
    frame["class"] = np.where(frame["label"].astype(str) == "Benign",
                              "benign", "attack")
    table = (frame.groupby(["bucket", "class"]).size().unstack(fill_value=0))
    for column in ("benign", "attack"):
        if column not in table.columns:
            table[column] = 0
    table = table[["benign", "attack"]].reset_index()

    # Keep the payload readable: merge gaps between capture sessions.
    timeline = [{"offset_s": int(r.bucket) * 60,
                 "benign": int(r.benign), "attack": int(r.attack)}
                for r in table.itertuples()]

    return {
        "alerts": dashboard_alerts,
        "timeline": timeline,
        "n_alerts": len(dashboard_alerts),
        "benchmarks": {
            "shap_tree": (shap_result or {}).get("benchmark"),
            "timeline_buckets": len(timeline),
        },
        "note": "Source IP is joined from lab/capture_logs/session_labels.csv.",
    }


