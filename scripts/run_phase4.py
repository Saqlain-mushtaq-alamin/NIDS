def run_response(ctx: Phase4Context, tiered_result: dict | None = None,
                 **_) -> dict:
    """Replay alerts through the tiered engine, then exercise the safety rails."""
    from src.response import ResponseEngine

    alerts = (tiered_result or {}).get("_alerts")
    if alerts is None:
        raise RuntimeError("Response component needs the tiered component "
                           "(run --components tiered response).")

    engine = ResponseEngine.from_config()
    log = []
    for alert in alerts:
        log.append(engine.execute({
            "confidence": alert["confidence"],
            "severity": alert["severity"],
            "source_ip": alert["source_ip"],
            "label": alert["label"],
            "alert_id": alert["alert_id"],
        }))

    stats = engine.stats()

    # --- NFR10 burst test: distinct hosts, more than the budget allows -----
    burst_engine = ResponseEngine(max_blocks_per_minute=10, dry_run=True)
    burst = []
    for i in range(15):
        burst.append(burst_engine.execute({
            "confidence": 0.99, "severity": "HIGH",
            "source_ip": f"10.0.0.{200 + i}",
            "label": "DoS", "alert_id": f"BURST-{i:02d}",
        }))
    burst_blocked = sum(1 for r in burst if r["action"] == "BLOCK")
    burst_stats = burst_engine.stats()
    burst_engine.shutdown()

    # --- manual rollback ---------------------------------------------------
    blocked_ips = [r["source_ip"] for r in log if r["action"] == "BLOCK"]
    rollback_target = blocked_ips[0] if blocked_ips else None
    rollback_ok = engine.rollback(rollback_target) if rollback_target else False

    # --- automatic TTL unblock --------------------------------------------
    ttl_engine = ResponseEngine(auto_unblock_seconds=0.4, dry_run=True)
    ttl_engine.execute({"confidence": 0.99, "severity": "HIGH",
                        "source_ip": "10.0.0.250", "label": "DoS"})
    was_blocked = "10.0.0.250" in ttl_engine.active_blocks
    time.sleep(0.9)
    expired = "10.0.0.250" not in ttl_engine.active_blocks
    ttl_engine.shutdown()

    history = engine.history()
    engine.shutdown()

    _save_response_csv(history)

    from collections import Counter
    counts = Counter(entry["action"] for entry in log)
    return {
        "n_replayed": len(log),
        "action_counts": dict(counts),
        "tiers_exercised": sorted(counts),
        "dry_run": stats["dry_run"],
        "unique_source_ips": sorted({r["source_ip"] for r in log}),
        "stats": stats,
        "log": log[:40],
        "burst_test": {
            "description": ("15 distinct high-confidence hosts replayed against "
                            "a 10 blocks/minute budget (synthetic addresses, "
                            "exercises NFR10)"),
            "n_attempted": len(burst),
            "max_blocks_per_minute": burst_stats["max_blocks_per_minute"],
            "n_blocked": burst_blocked,
            "n_downgraded": len(burst) - burst_blocked,
            "rate_limiter_engaged": burst_blocked <= burst_stats["max_blocks_per_minute"],
        },
        "rollback_demo": {
            "source_ip": rollback_target,
            "succeeded": bool(rollback_ok),
        },
        "auto_unblock_demo": {
            "ttl_seconds": 0.4,
            "blocked_before_ttl": bool(was_blocked),
            "expired_after_ttl": bool(expired),
            "succeeded": bool(was_blocked and expired),
        },
    }


