class Phase4Context:
    """
    Shared, lazily-built state for every Phase 4 component.

    One context per run keeps the split, the fitted models and the selected
    alerts identical across components, so the SHAP numbers, the DeepLIFT
    numbers, the Tier-1 summaries and the response replay all refer to the same
    flows.
    """

    def __init__(self, quick: bool = False, seed: int = 42,
                 n_alerts: int | None = None):
        self.quick = quick
        self.seed = seed
        self.n_alerts_override = n_alerts
        self._built = False

        self.df = None
        self.train_df = None
        self.test_df = None
        self.prep = None
        self.X_train = None
        self.y_train = None
        self.X_test = None
        self.y_test = None
        self.feature_names: list[str] = []
        self.class_names: list[str] = []
        self.xgb = None
        self.dnn = None
        self.device = None
        self.alert_rows: np.ndarray = np.array([], dtype=int)
        self.pred_labels: np.ndarray = np.array([], dtype=object)
        self.pred_index: np.ndarray = np.array([], dtype=int)
        self.confidence: np.ndarray = np.array([], dtype=float)
        self.source_ips: list[str] = []
        self.session_ids: list[str] = []
        self.timestamps: np.ndarray = np.array([], dtype=float)

    # -- construction ------------------------------------------------------
    def build(self) -> "Phase4Context":
        if self._built:
            return self
        from src.data.loader import load_dataset
        from src.data.preprocessor import Preprocessor
        from src.utils.reproducibility import set_global_seed

        set_global_seed(self.seed)

        print("[context] loading lab captures ...")
        self.df = load_dataset("lab-captured")
        self._attach_source_ips()

        self._split_sessions()
        self.prep = Preprocessor(drop_ip_port=True, normalization="robust",
                                 feature_mode="full")
        self.prep.fit(self.train_df)
        self.X_train, self.y_train = self.prep.transform(self.train_df)
        self.X_test, self.y_test = self.prep.transform(self.test_df)
        self.feature_names = list(self.prep.feature_names_)
        self.class_names = list(self.prep.class_names_)

        print(f"[context] features={len(self.feature_names)} "
              f"classes={len(self.class_names)} "
              f"train={self.X_train.shape[0]} test={self.X_test.shape[0]}")

        self._train_xgb()
        self._train_dnn()
        self._select_alerts()
        self._built = True
        return self

    # -- data --------------------------------------------------------------
    def _attach_source_ips(self) -> None:
        """Join session -> source IP from the lab capture log (real provenance)."""
        import pandas as pd

        log_path = _PROJECT_ROOT / "lab" / "capture_logs" / "session_labels.csv"
        self.session_to_ip: dict[str, str] = {}
        if log_path.is_file():
            log = pd.read_csv(log_path)
            if "session_id" in log.columns and "source_ip" in log.columns:
                self.session_to_ip = dict(zip(log["session_id"].astype(str),
                                              log["source_ip"].astype(str)))

    def _split_sessions(self) -> None:
        """
        Session-grouped split: no capture session appears in both folds.

        A flow-level split would let the model memorise session-specific
        statistics (rate, byte profile) that are identical on both sides, and
        every explanation would then be explaining a leak.
        """
        from sklearn.model_selection import StratifiedGroupKFold

        splitter = StratifiedGroupKFold(n_splits=3, shuffle=True,
                                        random_state=self.seed)
        train_idx, test_idx = next(
            splitter.split(self.df, self.df["label"],
                           groups=self.df["session_id"])
        )
        self.train_df = self.df.iloc[train_idx].reset_index(drop=True)
        self.test_df = self.df.iloc[test_idx].reset_index(drop=True)

        overlap = set(self.train_df["session_id"]) & set(self.test_df["session_id"])
        if overlap:  # pragma: no cover - would invalidate every number below
            raise RuntimeError(f"Session leakage between splits: {sorted(overlap)}")

    # -- models ------------------------------------------------------------
    def _train_xgb(self) -> None:
        from src.models.baseline_xgb import XGBBaseline

        n_estimators = 60 if self.quick else 150
        print(f"[context] training XGBoost ({n_estimators} trees) ...")
        self.xgb = XGBBaseline(n_estimators=n_estimators, max_depth=6,
                               learning_rate=0.1, random_state=self.seed)
        self.xgb.fit(self.X_train, self.y_train)

    def _train_dnn(self) -> None:
        """Small MLP classifier — the neural model DeepLIFT explains."""
        import torch
        import torch.nn as nn

        self.device = "cuda" if torch.cuda.is_available() else "cpu"
        torch.manual_seed(self.seed)

        n_features = self.X_train.shape[1]
        n_classes = len(self.class_names)
        self.dnn = nn.Sequential(
            nn.Linear(n_features, 64), nn.ReLU(), nn.Dropout(0.1),
            nn.Linear(64, 32), nn.ReLU(),
            nn.Linear(32, n_classes),
        ).to(self.device)
        self.dnn.eval()

        label_index = {name: i for i, name in enumerate(self.class_names)}
        y_idx = np.array([label_index[str(v)] for v in self.y_train])

        X = torch.as_tensor(self.X_train, dtype=torch.float32)
        y = torch.as_tensor(y_idx, dtype=torch.long)
        dataset = torch.utils.data.TensorDataset(X, y)
        loader = torch.utils.data.DataLoader(
            dataset, batch_size=256, shuffle=True,
            generator=torch.Generator().manual_seed(self.seed))

        optimizer = torch.optim.Adam(self.dnn.parameters(), lr=1e-3)
        criterion = nn.CrossEntropyLoss()
        epochs = 2 if self.quick else 12

        print(f"[context] training DNN ({epochs} epochs, {self.device}) ...")
        self.dnn.train()
        for epoch in range(epochs):
            total = 0.0
            for batch_X, batch_y in loader:
                batch_X = batch_X.to(self.device)
                batch_y = batch_y.to(self.device)
                optimizer.zero_grad()
                loss = criterion(self.dnn(batch_X), batch_y)
                loss.backward()
                optimizer.step()
                total += float(loss.item()) * len(batch_y)
            if epoch in (0, epochs - 1):
                print(f"    epoch {epoch + 1}/{epochs} loss={total / len(y):.4f}")
        self.dnn.eval()

        with torch.no_grad():
            logits = self.dnn(torch.as_tensor(self.X_test,
                                              dtype=torch.float32).to(self.device))
            preds = logits.argmax(dim=1).cpu().numpy()
        dnn_accuracy = float((np.array(self.class_names)[preds]
                              == np.asarray(self.y_test)).mean())
        self.dnn_accuracy = dnn_accuracy
        print(f"[context] DNN test accuracy={dnn_accuracy:.4f}")

    def dnn_proba(self, Z: np.ndarray) -> np.ndarray:
        """Softmax class probabilities for an ``(n, f)`` matrix."""
        import torch

        with torch.no_grad():
            tensor = torch.as_tensor(np.asarray(Z, dtype=np.float32),
                                     device=self.device)
            logits = self.dnn(tensor)
            return torch.softmax(logits, dim=1).cpu().numpy()

    # -- alerts ------------------------------------------------------------
    def _select_alerts(self) -> None:
        """
        Choose the flows that become alerts: predicted attacks above the
        confidence floor, sampled per predicted class so every attack type the
        detector can emit is represented in the explanations.
        """
        proba = self.xgb.predict_proba(self.X_test)
        self.pred_index = proba.argmax(axis=1)
        self.pred_labels = np.asarray(self.class_names, dtype=object)[self.pred_index]
        self.confidence = proba[np.arange(len(proba)), self.pred_index]

        max_alerts = self.n_alerts_override or (24 if self.quick else 150)
        min_confidence = 0.5

        eligible = np.where((self.pred_labels != "Benign")
                            & (self.confidence >= min_confidence))[0]
        if eligible.size == 0:  # pragma: no cover - detector raising nothing
            raise RuntimeError("Detector produced no alerts above the floor.")

        rng = np.random.default_rng(self.seed)
        by_class: dict[str, list[int]] = {}
        for row in eligible:
            by_class.setdefault(str(self.pred_labels[row]), []).append(int(row))

        # Round-robin over predicted classes: coverage beats random sampling.
        selected: list[int] = []
        per_class = max(1, int(np.ceil(max_alerts / max(len(by_class), 1))))
        while len(selected) < max_alerts and any(by_class.values()):
            for name in sorted(by_class):
                bucket = by_class.get(name) or []
                if not bucket:
                    continue
                pick = int(rng.choice(bucket))
                bucket.remove(pick)
                selected.append(pick)
                if len(selected) >= max_alerts:
                    break

        self.alert_rows = np.array(sorted(selected), dtype=int)
        self.source_ips = [self.session_to_ip.get(str(s), "unknown")
                           for s in self.test_df["session_id"].iloc[self.alert_rows]]
        self.session_ids = self.test_df["session_id"].astype(str).iloc[
            self.alert_rows].tolist()
        self.timestamps = self.test_df["timestamp_start"].astype(float).iloc[
            self.alert_rows].to_numpy()

    # -- convenience -------------------------------------------------------
    @property
    def alert_X(self) -> np.ndarray:
        return self.X_test[self.alert_rows]

    @property
    def alert_true_labels(self) -> np.ndarray:
        return np.asarray(self.y_test, dtype=object)[self.alert_rows]

    @property
    def n_alerts(self) -> int:
        return int(self.alert_rows.size)


_CONTEXTS: dict[tuple, Phase4Context] = {}


def get_context(quick: bool, seed: int, n_alerts: int | None = None) -> Phase4Context:
    key = (bool(quick), int(seed), n_alerts)
    if key not in _CONTEXTS:
        _CONTEXTS[key] = Phase4Context(quick=quick, seed=seed, n_alerts=n_alerts)
    return _CONTEXTS[key].build()


def _alert_metadata(ctx: Phase4Context, rows: np.ndarray | None = None) -> dict:
    rows = ctx.alert_rows if rows is None else rows
    return {
        "alert_id": [f"ALERT-{i:04d}" for i in range(len(rows))],
        "true_label": [str(v) for v in ctx.alert_true_labels],
        "predicted_label": [str(v) for v in ctx.pred_labels[rows]],
        "confidence": [float(v) for v in ctx.confidence[rows]],
        "session_id": list(ctx.session_ids),
        "source_ip": list(ctx.source_ips),
        "timestamp": [float(v) for v in ctx.timestamps],
    }


